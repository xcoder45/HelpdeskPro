-- HelpDesk Pro core schema.
-- All identifiers are deliberately explicit; no ORM is used.

CREATE TABLE roles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE CHECK (name IN ('employee', 'agent', 'admin')),
  description text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name text NOT NULL CHECK (length(btrim(first_name)) BETWEEN 1 AND 100),
  last_name text NOT NULL CHECK (length(btrim(last_name)) BETWEEN 1 AND 100),
  email text NOT NULL CHECK (length(btrim(email)) BETWEEN 3 AND 255),
  password_hash text NOT NULL CHECK (length(password_hash) >= 20),
  role_id integer NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
  is_active boolean NOT NULL DEFAULT true,
  is_demo boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE categories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE CHECK (length(btrim(name)) BETWEEN 2 AND 100),
  description text NOT NULL DEFAULT '',
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE subcategories (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id integer NOT NULL REFERENCES categories(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (length(btrim(name)) BETWEEN 2 AND 100),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (category_id, name)
);

CREATE TABLE sla_rules (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  priority text NOT NULL UNIQUE CHECK (priority IN ('Low', 'Medium', 'High', 'Critical')),
  response_minutes integer NOT NULL CHECK (response_minutes > 0),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE SEQUENCE ticket_code_seq AS bigint START WITH 1 INCREMENT BY 1;

CREATE OR REPLACE FUNCTION next_ticket_code()
RETURNS text
LANGUAGE sql
VOLATILE
AS $$
  SELECT format('HD-%s', lpad(nextval('ticket_code_seq')::text, 6, '0'))::text;
$$;

CREATE TABLE tickets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_code text NOT NULL DEFAULT next_ticket_code() UNIQUE CHECK (ticket_code ~ '^HD-[0-9]{6,}$'),
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 3 AND 200),
  description text NOT NULL CHECK (length(btrim(description)) >= 10),
  category_id integer NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
  subcategory_id integer REFERENCES subcategories(id) ON DELETE SET NULL,
  priority text NOT NULL CHECK (priority IN ('Low', 'Medium', 'High', 'Critical')),
  status text NOT NULL DEFAULT 'New' CHECK (status IN ('New', 'Assigned', 'In Progress', 'Pending', 'Resolved', 'Closed')),
  requester_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  assignee_id bigint REFERENCES users(id) ON DELETE SET NULL,
  sla_rule_id integer REFERENCES sla_rules(id) ON DELETE RESTRICT,
  response_due_at timestamptz NOT NULL,
  first_responded_at timestamptz,
  resolved_at timestamptz,
  closed_at timestamptz,
  resolution_notes text,
  is_demo boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT tickets_resolution_complete CHECK (
    status NOT IN ('Resolved', 'Closed')
    OR (resolution_notes IS NOT NULL AND length(btrim(resolution_notes)) > 0 AND resolved_at IS NOT NULL)
  ),
  CONSTRAINT tickets_closed_after_resolution CHECK (
    closed_at IS NULL OR (status = 'Closed' AND resolved_at IS NOT NULL)
  )
);

CREATE TABLE comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  author_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  body text NOT NULL CHECK (length(btrim(body)) BETWEEN 1 AND 5000),
  is_internal boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE ticket_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  actor_id bigint REFERENCES users(id) ON DELETE SET NULL,
  action text NOT NULL CHECK (length(btrim(action)) BETWEEN 1 AND 100),
  field_name text,
  old_value text,
  new_value text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE attachments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id bigint NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
  comment_id bigint REFERENCES comments(id) ON DELETE CASCADE,
  uploader_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  original_name text NOT NULL CHECK (length(btrim(original_name)) BETWEEN 1 AND 255),
  stored_name text NOT NULL UNIQUE CHECK (length(stored_name) BETWEEN 1 AND 255),
  mime_type text NOT NULL CHECK (length(btrim(mime_type)) BETWEEN 1 AND 100),
  size_bytes bigint NOT NULL CHECK (size_bytes > 0 AND size_bytes <= 5242880),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id bigint REFERENCES users(id) ON DELETE SET NULL,
  action text NOT NULL CHECK (length(btrim(action)) BETWEEN 1 AND 100),
  entity_type text NOT NULL CHECK (length(btrim(entity_type)) BETWEEN 1 AND 50),
  entity_id bigint,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  ip_address text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER roles_set_updated_at BEFORE UPDATE ON roles FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER users_set_updated_at BEFORE UPDATE ON users FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER categories_set_updated_at BEFORE UPDATE ON categories FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER subcategories_set_updated_at BEFORE UPDATE ON subcategories FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER sla_rules_set_updated_at BEFORE UPDATE ON sla_rules FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER tickets_set_updated_at BEFORE UPDATE ON tickets FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER comments_set_updated_at BEFORE UPDATE ON comments FOR EACH ROW EXECUTE FUNCTION set_updated_at();
