import { createHash } from 'node:crypto';
import { readdir, readFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createPool } from './pool.js';
import { env } from '../config/env.js';

const here = dirname(fileURLToPath(import.meta.url));
export const migrationsDirectory = resolve(here, '../migrations');

function checksum(sql) {
  return createHash('sha256').update(sql).digest('hex');
}

export async function runMigrations({
  connectionString = env.DATABASE_URL,
  directory = migrationsDirectory
} = {}) {
  const files = (await readdir(directory))
    .filter((name) => name.endsWith('.sql'))
    .sort();

  const db = createPool(connectionString);
  const applied = [];
  let client = null;
  let currentFilename = null;

  try {
    client = await db.connect();
    await client.query('BEGIN');
    // Serialize the whole migration run, including creation of the tracking
    // table. A per-file lock taken after CREATE TABLE leaves a race on a fresh
    // database where two processes can both try to create the table.
    await client.query(`SELECT pg_advisory_xact_lock(hashtext('helpdesk-pro-migrations'))`);
    await client.query(`
      CREATE TABLE IF NOT EXISTS schema_migrations (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        filename text NOT NULL UNIQUE,
        checksum text NOT NULL,
        applied_at timestamptz NOT NULL DEFAULT now()
      )
    `);

    for (const filename of files) {
      currentFilename = filename;
      const sql = await readFile(join(directory, filename), 'utf8');
      const digest = checksum(sql);
      const existing = await client.query(
        'SELECT checksum FROM schema_migrations WHERE filename = $1',
        [filename]
      );

      if (existing.rowCount > 0) {
        if (existing.rows[0].checksum !== digest) {
          throw new Error(`Migration ${filename} was modified after it was applied`);
        }
        applied.push({ filename, status: 'already-applied' });
        continue;
      }

      await client.query(sql);
      await client.query(
        'INSERT INTO schema_migrations (filename, checksum) VALUES ($1, $2)',
        [filename, digest]
      );
      applied.push({ filename, status: 'applied' });
    }

    await client.query('COMMIT');
  } catch (error) {
    if (client) await client.query('ROLLBACK');
    if (currentFilename && !error.message.startsWith(`Migration ${currentFilename} was modified`)) {
      throw new Error(`Migration ${currentFilename} failed: ${error.message}`, { cause: error });
    }
    throw error;
  } finally {
    if (client) client.release();
    await db.end();
  }

  return applied;
}

if (process.argv[1] && /[\\/]migrate\.js$/.test(process.argv[1])) {
  runMigrations()
    .then((results) => {
      for (const result of results) {
        console.log(`[migrate] ${result.status}: ${result.filename}`);
      }
    })
    .catch((error) => {
      console.error('[migrate] failed:', error.message || String(error));
      process.exitCode = 1;
    });
}
